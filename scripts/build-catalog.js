#!/usr/bin/env node
/* ==========================================================================
   SURF WETSUIT — catalogue index builder
   --------------------------------------------------------------------------
   Runs automatically on every Netlify deploy (see netlify.toml).

   WHY THIS EXISTS
   A browser cannot list the files in a folder, so index.html needs a manifest
   telling it which .md files exist. Without this script that manifest has to be
   edited by hand every time the owner adds a wetsuit in the Decap admin panel —
   easy to forget, and then the new suit never appears.

   This script scans content/products/*.md, reads their front matter, and
   regenerates content/products/index.json. Run it locally too:
       node scripts/build-catalog.js
   ========================================================================== */

const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const PRODUCTS_DIR = path.join(ROOT, "content", "products");
const INDEX_FILE = path.join(PRODUCTS_DIR, "index.json");

const SIZES = ["S", "M", "L", "XL"];

function unquote(value) {
  const quoted = /^(['"])([\s\S]*)\1$/.exec(value);
  if (quoted) return quoted[2];
  return value.replace(/\s+#.*$/, "").trim();
}

/* Minimal front-matter reader — scalars only, which is all Decap writes. */
function parseFrontMatter(raw) {
  const match = /^\uFEFF?---\s*\r?\n([\s\S]*?)\r?\n---/.exec(raw);
  if (!match) return {};

  const data = {};
  match[1].split(/\r?\n/).forEach((line) => {
    if (!line.trim() || /^\s*#/.test(line)) return;
    const idx = line.indexOf(":");
    if (idx === -1) return;
    const key = line.slice(0, idx).trim();
    let value = line.slice(idx + 1).trim();
    if (!key) return;

    value = unquote(value);
    if (value === "true") value = true;
    else if (value === "false") value = false;
    else if (/^-?\d+(\.\d+)?$/.test(value)) value = Number(value);

    data[key] = value;
  });
  return data;
}

function main() {
  if (!fs.existsSync(PRODUCTS_DIR)) {
    console.error(`[catalog] missing folder: ${PRODUCTS_DIR}`);
    process.exit(1);
  }

  const files = fs
    .readdirSync(PRODUCTS_DIR)
    .filter((f) => f.toLowerCase().endsWith(".md"))
    .sort();

  const featured = [];
  const catalogFiles = [];
  const warnings = [];

  files.forEach((file) => {
    const raw = fs.readFileSync(path.join(PRODUCTS_DIR, file), "utf8");
    const data = parseFrontMatter(raw);

    catalogFiles.push(file);

    const size = String(data.size || "").toUpperCase();
    if (!SIZES.includes(size)) {
      warnings.push(`${file}: size "${data.size || ""}" is not one of S/M/L/XL (it will not match any filter chip)`);
    }
    if (!data.price && data.price !== 0) warnings.push(`${file}: no price set`);
    if (!data.image) warnings.push(`${file}: no image set`);
    if (data.featured === true) featured.push(file.replace(/\.md$/i, ""));
  });

  const payload = {
    note: "Generated by scripts/build-catalog.js on every Netlify deploy. Do not edit by hand — it is overwritten. To change which wetsuits show on the site, add or edit the .md files in this folder.",
    generatedAt: new Date().toISOString(),
    count: catalogFiles.length,
    featured,
    files: catalogFiles
  };

  fs.writeFileSync(INDEX_FILE, JSON.stringify(payload, null, 2) + "\n", "utf8");

  console.log(`[catalog] wrote ${path.relative(ROOT, INDEX_FILE)} with ${catalogFiles.length} product(s)`);
  if (featured.length) console.log(`[catalog] featured: ${featured.join(", ")}`);
  warnings.forEach((w) => console.warn(`[catalog] warning — ${w}`));
  if (warnings.length) console.warn(`[catalog] ${warnings.length} warning(s); deploy continues.`);
}

main();
